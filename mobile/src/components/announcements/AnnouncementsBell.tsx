import { router, type Href } from "expo-router";
import { StyleSheet, View } from "react-native";

import { MESSAGES_PATH, unreadAccessibilityValue, unreadBadgeLabel } from "@/announcements/logic";
import { useAnnouncements } from "@/announcements/use-announcements";
import { AppText } from "@/components/AppText";
import { IconButton } from "@/components/IconButton";
import { LRI, PDI } from "@/components/markdown/links";
import { useTheme } from "@/theme/ThemeProvider";

/**
 * «رسائل ريحان» bell beside the settings gear (web AnnouncementsBell, plan
 * D3). While `unread_count > 0` it carries a count badge in the theme's
 * primary colour («9+» above 9). No data (loading / failed) → no badge.
 */
export function AnnouncementsBell({ testID }: { testID?: string }) {
  const { colours } = useTheme();
  const { data } = useAnnouncements();
  const count = data?.unread_count ?? 0;
  const badge = unreadBadgeLabel(count);

  return (
    <View>
      <IconButton
        icon="bell"
        label="رسائل ريحان"
        value={unreadAccessibilityValue(count)}
        // Cast: the typed-routes manifest is regenerated by `expo start`, not by tsc.
        onPress={() => router.push(MESSAGES_PATH as Href)}
        testID={testID}
      />
      {badge ? (
        <View
          pointerEvents="none"
          accessibilityElementsHidden
          importantForAccessibility="no-hide-descendants"
          style={[styles.badge, { backgroundColor: colours.primary, borderColor: colours.surface1 }]}
          testID={testID ? `${testID}-badge` : undefined}
        >
          {/* LTR isolate: «9+» must not reorder to «+9» inside RTL text. */}
          <AppText weight={700} tone="onPrimary" align="center" maxFontSizeMultiplier={1} style={styles.badgeText}>
            {`${LRI}${badge}${PDI}`}
          </AppText>
        </View>
      ) : null}
    </View>
  );
}

const styles = StyleSheet.create({
  badge: {
    position: "absolute",
    top: 4,
    end: 2,
    minWidth: 18,
    minHeight: 18,
    paddingHorizontal: 4,
    borderRadius: 9,
    borderWidth: 1.5,
    alignItems: "center",
    justifyContent: "center",
  },
  badgeText: { fontSize: 11, lineHeight: 15, includeFontPadding: false, textAlignVertical: "center" },
});

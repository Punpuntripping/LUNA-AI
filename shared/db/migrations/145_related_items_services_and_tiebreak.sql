-- ── 0. PREFLIGHT ───────────────────────────────────────────────────────────
-- Existence and shape only. Every column name in this file is written out
-- literally and never resolved at run time (143's rule: a migration that
-- discovers its own column names cannot be reviewed by reading it, and it turns
-- a pipeline rename from a loud failure into a silent behaviour change). What a
-- bare CREATE would not tell you are the three things checked here, each of
-- which fails SILENTLY otherwise:
--   (a) 143 has not been applied — §3 would then fail on a missing table, but
--       the message would not say why;
--   (b) services.embedding is gone (the D6 drop above) — the compliance branch
--       would compile and then error only when refreshed;
--   (c) the embedding is present but EMPTY for the canonical guides — that
--       produces an empty topic_base, a silently unchanged 83-of-337 wing, and
--       no error at all. This is exactly the regression nobody would notice.
do $$
declare
  v_dim  text;
  v_tot  integer;
  v_emb  integer;
begin
  if to_regclass('public.related_items') is null
     or to_regclass('public.related_axis_weights') is null then
    raise exception
      '145 §0: public.related_items / related_axis_weights missing. Apply '
      '143_related_items.sql FIRST — this migration extends it, it does not '
      'replace it.';
  end if;

  if to_regclass('public.service_guides') is null
     or to_regclass('public.services')    is null
     or to_regclass('public.cases')       is null then
    raise exception
      '145 §0: a corpus relation is missing (need public.service_guides, '
      'public.services, public.cases). Wrong database?';
  end if;

  select format_type(a.atttypid, a.atttypmod)
    into v_dim
    from pg_attribute a
   where a.attrelid = 'public.services'::regclass
     and a.attname  = 'embedding'
     and a.attnum > 0
     and not a.attisdropped;

  if v_dim is null then
    raise exception
      '145 §0: public.services.embedding does not exist. It is the ENTIRE base '
      'axis for خدمات in this migration (§4 compliance branch). If it was '
      'dropped per reg_search_unified_topics D6, revert that branch to 143''s '
      'empty topic_base stub or repoint it at search_topics '
      '(source_type = ''service'') before applying this file.';
  end if;

  -- Coverage. The map is guide -> service -> embedding, INNER at every step:
  -- a guide whose service row vanished has no embedding and simply gets no
  -- topic base (it keeps its sector/entity bonus tier).
  select count(*) into v_tot
    from public.service_guides g
   where coalesce(g.is_canonical, true);

  select count(*) into v_emb
    from public.service_guides g
    join public.services sv on sv.id = g.service_id
   where coalesce(g.is_canonical, true)
     and sv.embedding is not null;

  if v_emb = 0 then
    raise exception
      '145 §0: 0 of % canonical service_guides reach a non-null '
      'services.embedding. topic_base would be empty and the خدمات wing would '
      'stay starved at 83 of 337 sources — silently, with no error.', v_tot;
  end if;

  -- most_used_rank carries the compliance tiebreak (§4). Checked here because a
  -- plpgsql body is only SYNTAX-checked at CREATE time — a missing column
  -- inside it does not surface until the first refresh, and by then the
  -- migration reads as "applied cleanly".
  if not exists (
    select 1 from pg_attribute a
     where a.attrelid = 'public.service_guides'::regclass
       and a.attname  = 'most_used_rank'
       and a.attnum > 0 and not a.attisdropped
  ) then
    raise exception
      '145 §0: public.service_guides.most_used_rank does not exist. It is the '
      'compliance tiebreak (migration 142''s library_compliance_v selects it). '
      'Either re-point §4''s compliance docs CTE or drop to '
      'related_stable_tiebreak(f.b) as regulation/circular do.';
  end if;

  -- Drift is reported, not enforced: the corpus is pipeline-ingested and SHOULD
  -- grow. Read the notice. 2026-08-23 measured 337 / 337 and vector(1024);
  -- most_used_rank had 0 NULLs at wing build (compliance_service_guides §1), and
  -- any that appear now simply sort last.
  raise notice '145 §0: services.embedding is % · canonical guides % · with an '
               'embedding % · unranked (most_used_rank NULL) % '
               '(2026-08-23: vector(1024) · 337 · 337 · 161)',
               v_dim, v_tot, v_emb,
               (select count(*) from public.service_guides g
                 where coalesce(g.is_canonical, true)
                   and g.most_used_rank is null);
end $$;


-- ── 1. THE TWO NEW KNOBS (same discipline as 143 §0) ───────────────────────
-- 143 keeps its calibration constants behind one-line IMMUTABLE functions so a
-- Wave D retune is one edit with no data migration and nothing downstream
-- hardcodes a number. These two follow it exactly. They belong next to
-- related_floor() / related_target_share() conceptually; they live here because
-- 143 is applied and is never edited.
--
-- ── HOW 0.50 WAS CHOSEN — the measured distribution, not a guess ───────────
-- Full pairwise cosine over the 337 canonical guides, 56,616 UNORDERED pairs,
-- measured on prod 2026-08-23:
--
--     p50 0.250 · p90 0.382 · p99 0.559 · p99.9 0.736 · max 0.887
--
-- Coverage and degree at candidate thresholds (directed edges = 2x unordered):
--
--     threshold   guides covered   directed edges   avg degree
--       0.35        337 of 337         17,082          50.7
--       0.40        337                 8,782          26.1
--       0.45        333                 4,600          13.8
--       0.50        310 (92%)           2,432           7.85   <- chosen
--       0.60        229                   692           3.0
--
-- 0.50 keeps 1,216 of 56,616 unordered pairs — 2.15%, i.e. the ~97.9th
-- percentile of the pair distribution, sitting between p90 (0.382) and p99
-- (0.559). (An earlier note called it "just above p99"; the table's own
-- arithmetic says just below. The threshold is right, the label was not.)
--
-- Why that point and not a neighbour:
--   • avg degree 7.85 is the smallest value that still fills the cap of 7 for a
--     typical guide, so the strip is full without storing near-random pairs.
--   • 0.45 buys 23 more covered guides and DOUBLES the edge count with pairs
--     sitting around p95 — that is noise bought at 2x the storage.
--   • 0.60 is honest but thin: 108 guides lose their base axis to gain nothing.
--   • The 27 guides left uncovered at 0.50 are not orphaned. They fall through
--     to the sector/entity bonus tier exactly as they do today.
--
-- ⚠ THE EFFECTIVE FLOOR IS SLIGHTLY HIGHER THAN 0.50 FOR A BONUS-LESS PAIR.
--   §1's map sends 0.50 -> base 0, so a pair with no shared sector or entity
--   needs base >= related_floor() = 0.15 to be STORED, i.e.
--   sim >= 0.50 + 0.15 * (0.887 - 0.50) / 3.0 = 0.5194. Pairs between 0.50 and
--   0.5194 survive only if a sector/entity bonus carries them. Expect the
--   realised coverage to be a little under the 310 measured at the raw cut;
--   §7's first query reports the actual number.
--
-- ⚠ BOTH ANCHORS ARE MODEL-SPECIFIC. They are fitted to the embedding that was
--   in services.embedding on 2026-08-23. Re-embedding the corpus with a
--   different model moves the whole distribution and both numbers must be
--   re-fitted from a fresh percentile dump — a cosine threshold is not
--   portable across embedding spaces the way a rank threshold would be. That
--   trade was taken deliberately: a rank/percentile floor cannot tell a
--   genuinely tight corpus from a genuinely diffuse one, and it would have
--   re-created Defect 1's exact failure (a fraction that does not transfer).

create or replace function public.related_service_sim_floor()
returns real language sql immutable parallel safe as $$
  select 0.50::real;
$$;

comment on function public.related_service_sim_floor() is
  'خدمات base axis: the minimum services.embedding cosine similarity at which a '
  'pair is worth a base at all, and the LOWER anchor of the base map. 0.50 = '
  'the ~97.9th percentile of the 56,616 pairwise similarities measured on prod '
  '2026-08-23 (p50 0.250 / p90 0.382 / p99 0.559 / max 0.887); it covers 310 of '
  '337 guides at avg degree 7.85. Model-specific — re-fit if services.embedding '
  'is ever rebuilt with a different model. Changing it requires re-running '
  'refresh_related_items(''compliance'').';

create or replace function public.related_service_sim_max()
returns real language sql immutable parallel safe as $$
  select 0.887::real;
$$;

comment on function public.related_service_sim_max() is
  'خدمات base axis: the UPPER anchor of the base map — the similarity that '
  'earns the full base of 3.0. 0.887 is the observed corpus maximum on prod '
  '2026-08-23, which also proves no two canonical guides share one '
  'services.embedding (that would read as 1.0). A pair above the anchor is '
  'clamped, so a re-ingest cannot produce a base > 3.0; it would just flatten '
  'the top of the scale, which is the signal to re-fit both anchors.';


-- ── 2. TIEBREAK HELPERS ────────────────────────────────────────────────────
-- Three small functions. All IMMUTABLE and PARALLEL SAFE so they inline into
-- the refresh queries; none carries a `set search_path` clause (that would
-- block inlining) and every reference inside is schema-qualified — same
-- reasoning as 143's related_canonical_entity().

-- 2.1 The Hijri year, mirroring shared/seo/judgment_naming.py:hijri_year().
-- cases.date_hijri is FREE TEXT, not a date: the corpus holds «1445/06/01»,
-- «15 ربيع الأول 1445», «29 ذو القعدة 1443» and bare «1446». The Python side
-- translates Arabic-Indic digits, scans every 4-digit run left to right and
-- takes the first one in the plausible Hijri range 1300–1500. This is the same
-- algorithm, character for character, so a judgment's derived title and its
-- tiebreak can never disagree about what year it is.
--   WITH ORDINALITY is load-bearing: regexp_matches('g') returns a set, and
--   `limit 1` without an explicit order is only accidentally left-to-right.
create or replace function public.related_hijri_year(p_text text)
returns integer language sql immutable parallel safe as $$
  select t.y
    from (
      select (m.arr)[1]::int as y, m.ord
        from regexp_matches(
               translate(coalesce(p_text, ''), '٠١٢٣٤٥٦٧٨٩', '0123456789'),
               '\d{4}', 'g') with ordinality as m(arr, ord)
    ) t
   where t.y between 1300 and 1500
   order by t.ord
   limit 1;
$$;

comment on function public.related_hijri_year(text) is
  'First plausible 4-digit Hijri year (1300–1500) in a free-text date. Mirrors '
  'shared/seo/judgment_naming.py:hijri_year() exactly — Arabic-Indic digits '
  'translated, matches scanned left to right, NULL when none is plausible.';

-- 2.2 Hijri text -> an approximate Gregorian date.
-- G = floor(H - H/33 + 622): 1445 -> 2023, 1300 -> 1882, 1500 -> 2076. Only the
-- YEAR is recoverable, so the date is pinned to 1 July — mid-year is the
-- least-biased choice when the true date is uniform inside the year and has to
-- be compared against rows that DO carry a full date_gregorian.
-- The residual consequence is stated where it matters (§4, judgment branch):
-- every ruling known only to its Hijri year collapses onto one of ~20 dates and
-- those rows tie with each other. That is as much precision as the data holds.
create or replace function public.related_hijri_date(p_text text)
returns date language sql immutable parallel safe as $$
  select make_date(floor(h.y - h.y / 33.0 + 622.0)::int, 7, 1)
    from (select public.related_hijri_year(p_text) as y) h
   where h.y is not null;
$$;

comment on function public.related_hijri_date(text) is
  'Approximate Gregorian date for a free-text Hijri date, pinned to 1 July of '
  'the converted year (G = floor(H - H/33 + 622)). Year precision only — used '
  'as the fallback recency key for the 7,867 judgments that carry date_hijri '
  'but no date_gregorian. NULL in, NULL out.';

-- 2.3 A stable, unbiased shuffle in [0,1) keyed on the target id.
-- This is the tiebreak for أنظمة and تعاميم and it deliberately carries NO
-- signal — see the §4 branch comments for why the two candidates that DO carry
-- signal were both rejected. Its one job is to make the order REPRODUCIBLE:
-- with a constant tiebreak, `order by score desc, tiebreak desc` over a block
-- of equal scores is still whatever the planner returns, and it may return
-- something different next time.
--   hashtext() is deterministic within a server, which is all that is required
--   — the value is recomputed from scratch on every refresh and is never
--   compared against a stored one.
create or replace function public.related_stable_tiebreak(p_id text)
returns real language sql immutable parallel safe as $$
  select ((hashtext(p_id)::bigint + 2147483648)::double precision
          / 4294967296.0)::real;
$$;

comment on function public.related_stable_tiebreak(text) is
  'Deterministic uniform shuffle in [0,1) from a target id. The related_items '
  'tiebreak for regulation and circular: it asserts no quality ordering, it '
  'only removes planner nondeterminism from a block of equal scores. Unbiased '
  'on purpose — alphabetical order was the alternative and it would have '
  'systematically front-loaded one doc-type prefix («نظام…» / «تعميم…»).';


-- ── 3. related_items.tiebreak + the lookup index + the comment refresh ─────

-- Metadata-only on PG11+ (constant default, no rewrite) even at 648 MB. The
-- DEFAULT is what makes the intermediate state safe: every row 143 already
-- wrote reads 0 until its corpus is refreshed, so `score desc, tiebreak desc`
-- degrades to today's `score desc` — never to a WRONG order.
alter table public.related_items
  add column if not exists tiebreak real not null default 0;

-- The index swap. Conditional so a re-apply is a no-op instead of a second
-- rebuild: only drop while the index still has 143's three-column shape.
-- Not CONCURRENTLY — see the apply-cost note in the header.
do $$
begin
  if exists (
    select 1 from pg_indexes
     where schemaname = 'public'
       and indexname  = 'idx_related_items_lookup'
       and indexdef not like '%tiebreak%'
  ) then
    raise notice '145 §3: rebuilding idx_related_items_lookup with tiebreak '
                 '(ACCESS EXCLUSIVE on related_items for a few seconds)';
    execute 'drop index public.idx_related_items_lookup';
  end if;
end $$;

create index if not exists idx_related_items_lookup
  on public.related_items (source_type, source_id, score desc, tiebreak desc);

comment on index public.idx_related_items_lookup is

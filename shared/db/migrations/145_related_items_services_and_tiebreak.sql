-- ── DEFECT 1 — THE خدمات WING IS STARVED, AND ITS BEST SIGNAL IS UNUSED ─────
-- Only 83 of 337 guides carry any edge at all. The cause is not the floor, it
-- is the SHAPE of the scarcity normalizer: related_target_share() = 0.007 is a
-- FRACTION OF THE CORPUS, and a fraction does not transfer across corpus sizes.
-- On أنظمة (N = 3,951) it means "scarce = 27.7 documents", which is a real
-- population of sectors. On خدمات (N = 337) the same 0.007 means "scarce = 2.4
-- documents" — so virtually no sector clears related_gen_floor() = FLOOR/2 and
-- the generator produces almost nothing. Lowering TARGET_SHARE is not the fix:
-- it is one global knob shared by four corpora, and moving it to suit a
-- 337-document corpus would re-price all 1.5M judgment edges.
--
-- The fix is to stop asking the scarcity axes to carry a wing they cannot
-- carry, and to give خدمات the base axis it has always had and never used:
-- `public.services.embedding` — a 1024-dim vector with an HNSW index
-- (idx_svc_embedding) that every one of the 337 canonical guides reaches
-- through service_guides.service_id. This fills 143's compliance Wave E seam
-- with VECTORS instead of BM25, which is strictly better here: BM25 over
-- search_topics would have been ~1.4 topic sentences per service, while the
-- embedding is a whole-service representation that already exists and is
-- already indexed.
--
--   • FULL PAIRWISE COSINE — no KNN, no top-K. 337 x 336 = 113,232 ordered
--     pairs is ~0.3s of vector arithmetic. A top-K generator would violate D6
--     ("never a top-N per source": a top-10 whose members are all unpublished
--     renders an empty strip while good candidates sit at rank 11+), and at
--     this size there is no reason to reach for one. idx_svc_embedding is NOT
--     used and is not needed — an HNSW index answers "nearest to a probe", and
--     this is an all-pairs scan.
--   • The embedding side EMITS ITS OWN CANDIDATES as well as a base. 143 §0's
--     completeness argument makes the axis generators lossless only for pairs
--     with base = 0; a pair whose base is what carries it over the floor has to
--     be generated by the base side or it is silently lost. 143's compliance
--     `cand` already unions `topic_base`, so this is satisfied by filling the
--     CTE — but it is the reason the CTE must return candidate rows and not
--     just a lookup table of bases.
--   • reason = 'service_embedding', a NEW value — not 'topic_bm25'. They are
--     different evidence and Wave D samples on `reason`. 'topic_bm25' stays
--     reserved for the تعاميم seam, which is still empty.
--
-- ── DEFECT 2 — THE JUDGMENT STRIP IS A PERFECT TIE ─────────────────────────
-- Measured: 22 courts clear related_gen_floor(), and 0 of those 22 contain more
-- than one entity value. Court and entity are therefore both CONSTANT within a
-- court, so bonus = least(2.0, entity_term + w(court)) is constant too, and
-- base is 0 by construction on this corpus. Every candidate for a given
-- judgment scores identically — 0.161 for all 532 others in the largest tax
-- chamber. `order by score desc limit 7` over 532 identical scores returns
-- whatever the planner happens to produce, and it is free to produce something
-- different on the next call: the top 7 is arbitrary AND unstable.
--
-- The fix is a second, separate ordering key: `related_items.tiebreak`, a
-- property of the TARGET normalized to [0,1], higher = shown first. The backend
-- orders by `score desc, tiebreak desc` and the extended lookup index serves
-- that in one scan.
--
-- ⚠ THE TIEBREAK IS NOT FOLDED INTO score. `score = base + bonus` is a
--   production invariant that is verified directly
--   (`abs(score - (base+bonus)) > 0.001` must return 0 rows). Folding a
--   recency term into score would break that check, would make the floor
--   comparison meaningless, and would let a recent-but-weak edge outrank a
--   strong one. It is a separate column and it is only ever an ORDER BY key —
--   nothing thresholds it, so only its monotonicity matters, never its spacing.
--

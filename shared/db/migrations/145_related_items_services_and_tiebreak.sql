  '''service_embedding'' (145) = a خدمات pair scored on services.embedding '
  'cosine; ''topic_bm25'' stays reserved for the تعاميم Wave E seam, which is '
  'still empty. They are different evidence and are never merged.';


-- ── 4. refresh_related_items(p_corpus) — redefined whole ───────────────────
-- 143's functions are `create or replace`, so the whole body is restated here.
-- Diff against 143 §7, branch by branch:
--
--   regulation  + `tiebreak` in the INSERT column list
--               + related_stable_tiebreak(f.b) in the final SELECT
--               (nothing else changes — no CTE is touched)
--   circular    same two lines, same reasoning
--   compliance  + the Wave E seam FILLED: `svec` and a real `topic_base`
--               + reason flips to 'service_embedding' when a base is present
--               + `docs` wrapped to carry the most_used_rank tiebreak
--               + `tiebreak` in the INSERT list and db.tiebreak in the SELECT
--   judgment    + `docs` wrapped to carry the recency tiebreak
--               + `tiebreak` in the INSERT list and db.tiebreak in the SELECT
--
-- The score itself is UNCHANGED everywhere: score = base + bonus, stored iff
-- >= related_floor(). Nothing in this migration re-prices an existing edge on
-- regulation, circular or judgment — those three corpora will come back with
-- exactly the row counts 143 produced, plus a populated tiebreak column.
--
-- ⚠ Note where the tiebreak is read from in each branch. It is a property of
--   the TARGET, i.e. of `b`. On compliance and judgment it rides on the `docs`
--   CTE, which `final` ALREADY joins as `db` — so it costs zero extra joins,
--   even on the judgment branch's 1.45M output rows. On regulation and circular
--   it is a pure function of the id and is computed inline, which keeps those
--   two branches a two-line diff.

create or replace function public.refresh_related_items(p_corpus text)
returns integer
language plpgsql
security definer
-- ⚠ `extensions` IS REQUIRED HERE, and is not tidiness. pgvector's `<=>`
--   operator lives in the `extensions` schema on Supabase; 143 pinned this
--   function to `public` alone, which was harmless until the compliance branch
--   below started using cosine distance. A plpgsql body is only SYNTAX-checked
--   at CREATE time, so 145 applied CLEANLY and then died on the first
--   refresh_related_items('compliance') with
--     «operator does not exist: extensions.vector <=> extensions.vector».
--   `extensions` is owned by supabase_admin and is not writable by any app
--   role, so widening the path does not widen the SECURITY DEFINER blast
--   radius. Anything added to this body that touches a vector needs it.
set search_path = public, extensions
-- ⚠ THIS CLAUSE DOES NOT PROTECT THIS FUNCTION'S OWN BODY (143, learned the
--   hard way on 2026-08-23). statement_timeout is armed when the OUTER
--   statement starts, from the value in force at that moment; a function-local
--   SET changes the setting for later statements, never for the one already
--   running. `select public.refresh_related_items('judgment')` is bounded by
--   the CALLER's timeout — 2 minutes under Supabase's pooler — and the judgment
--   branch takes ~13 minutes. The caller must raise it; §6 has the recipe. The
--   clause is kept because it is the right ceiling for the weekly cron job,
--   whose session inherits no shorter one.
set statement_timeout = '900s'
as $$
declare
  v_count integer := 0;
begin

  -- ══ أنظمة ════════════════════════════════════════════════════════════════
  if p_corpus = 'regulation' then
    delete from public.related_items where source_type = 'regulation';

    insert into public.related_items
      (source_type, source_id, target_type, target_id, score, base, bonus, reason, tiebreak)
    with
    docs as (
      select r.id::text as id,
             public.related_canonical_entity(nullif(btrim(r.entity_ref::text), '')) as entity,
             coalesce(r.sectors, '{}'::text[]) as sectors
        from public.regulations_v2 r
    ),
    ds as (   -- the (doc, sector) inverted index; see 143 §7.2
      select d.id, s.v as sector
        from docs d, unnest(d.sectors) s(v)
       where nullif(btrim(s.v), '') is not null
    ),
    sw as (select w.value, w.weight from public.related_axis_weights w
            where w.corpus = 'regulation' and w.axis = 'sector'),
    ew as (select w.value, w.weight from public.related_axis_weights w
            where w.corpus = 'regulation' and w.axis = 'entity'),

    -- ── base sources (plan §3.3), max() over any duplicate edge row ────────
    b_doc as (
      select e.a, e.b,
             max(case when e.agreement = 'both' then 5.0 else 3.5 end)::real as base
        from public.related_reg_document_edges e
       group by e.a, e.b
    ),
    b_sub as (
      -- 1.5 + 1.5*(score-0.6)/0.4 -> [1.5, 3.0]. Clamped both ends: the ingest
      -- threshold is 0.6 today, and a future re-run at a lower threshold must
      -- not push the base under the 1.2 cluster tier.
      select e.a, e.b,
             least(3.0, greatest(1.5,
               1.5 + 1.5 * (max(e.score) - 0.6) / 0.4))::real as base
        from public.related_reg_subject_edges e
       group by e.a, e.b
    ),
    b_clu as (
      select distinct m1.reg_id as a, m2.reg_id as b, 1.2::real as base
        from public.related_reg_subject_members m1
        join public.related_reg_subject_members m2
          on m2.core_subject_id = m1.core_subject_id
         and m2.reg_id <> m1.reg_id
    ),

    -- ── candidates ─────────────────────────────────────────────────────────
    cand as (
      select u.a, u.b from (
          select a, b from b_doc
        union
          select a, b from b_sub
        union
          select a, b from b_clu
        union
          -- entity generator, guarded (143 §0). On أنظمة this fires only for
          -- entities with n <= 100 documents, so the four biggest issuing
          -- authorities generate nothing at all.
          select d1.id as a, d2.id as b
            from docs d1
            join ew on ew.value = d1.entity
                   and ew.weight >= public.related_gen_floor()
            join docs d2 on d2.entity = d1.entity and d2.id <> d1.id
        union
          -- sector generator, guarded by the FULL sector_term (the HAVING is
          -- the guard; a pair only survives if its shared sectors alone carry
          -- half the floor).
          select p.a, p.b from (
            select x.id as a, y.id as b,
                   least(1.0, (count(*) * (count(*) + 1) / 2.0) * sum(sw.weight))
                     as sector_term
              from ds x
              join ds y  on y.sector = x.sector and y.id <> x.id
              join sw    on sw.value = x.sector
             group by x.id, y.id
          ) p
          where p.sector_term >= public.related_gen_floor()
      ) u
      where u.a is not null and u.b is not null and u.a <> u.b
    ),

    -- Shared sectors for every candidate pair, whatever generated it. Note
    -- this uses ALL shared sectors, including ones far below the generation
    -- threshold: generation filters the GENERATOR, scoring uses everything.
    pair_sec as (
      select c.a, c.b, count(*)::int as k,
             sum(sw.weight)::double precision as w_sum
        from cand c
        join ds x on x.id = c.a
        join ds y on y.id = c.b and y.sector = x.sector
        join sw   on sw.value = x.sector
       group by c.a, c.b
    ),

    scored as (
      select c.a, c.b,
             bd.base as base_doc, bs.base as base_sub, bc.base as base_clu,
             least(2.0,
                   (case when da.entity is not null and da.entity = db.entity
                         then coalesce(ew.weight, 0) else 0 end)
                 + coalesce(least(1.0, (ps.k * (ps.k + 1) / 2.0) * ps.w_sum), 0)
             )::real as bonus
        from cand c
        join docs da on da.id = c.a
        join docs db on db.id = c.b
        left join b_doc    bd on bd.a = c.a and bd.b = c.b
        left join b_sub    bs on bs.a = c.a and bs.b = c.b
        left join b_clu    bc on bc.a = c.a and bc.b = c.b
        left join pair_sec ps on ps.a = c.a and ps.b = c.b
        left join ew          on ew.value = da.entity and da.entity = db.entity
    ),
    final as (
      -- greatest() ignores NULLs, so this is "the max of whichever apply".
      select s.a, s.b,
             coalesce(greatest(s.base_doc, s.base_sub, s.base_clu), 0)::real as base,
             s.bonus,
             case
               when coalesce(greatest(s.base_doc, s.base_sub, s.base_clu), 0) = 0
                 then 'bonus_only'
               when s.base_doc is not null
                    and s.base_doc >= coalesce(s.base_sub, 0)
                    and s.base_doc >= coalesce(s.base_clu, 0)
                 then case when s.base_doc >= 5.0 then 'document_relation_both'
                           else 'document_relation_one_way' end
               when s.base_sub is not null and s.base_sub >= coalesce(s.base_clu, 0)
                 then 'core_subject_relation'
               else 'core_subject_member'
             end as reason
        from scored s
    )
    -- TIEBREAK (145). A stable shuffle, carrying no signal, and both of the
    -- alternatives that DO carry signal were rejected on the merits:
    --   • seo_item_meta.rank (the usage rank from migration 116) is THE hub
    --     ordering key and would be the obvious choice — but 143's D5 contract
    --     is that NOTHING in this graph reads seo_item_meta. Publish state must
    --     not leak into the stored edges, and `rank` is NULL for every
    --     unranked/unpublished نظام, so half the corpus would silently sort
    --     last inside the graph rather than at render time.
    --   • Alphabetical (the wing's own secondary sort) is deterministic but
    --     BIASED: Arabic أنظمة titles almost all open with «نظام» or «لائحة»,
    --     so it would front-load one doc-type prefix in every strip.
    -- If a verified issue-date column is ever confirmed on regulations_v2, this
    -- is the one expression to replace — the judgment branch below is the
    -- worked example of the cume_dist recency shape.
    select 'regulation', f.a, 'regulation', f.b,
           (f.base + f.bonus)::real, f.base, f.bonus, f.reason,
           public.related_stable_tiebreak(f.b)
      from final f
     where (f.base + f.bonus) >= public.related_floor();

  -- ══ تعاميم ═══════════════════════════════════════════════════════════════
  elsif p_corpus = 'circular' then
    delete from public.related_items where source_type = 'circular';

    insert into public.related_items
      (source_type, source_id, target_type, target_id, score, base, bonus, reason, tiebreak)
    with
    docs as (
      -- circulars.entity_ref is this corpus's own key space (5 distinct values,
      -- 296–619 docs each — every one of them is worth ~0 after 143 §0's fix,
      -- which is the correct reading of "both issued by the same ministry").
      select ci.id::text as id,
             public.related_canonical_entity(nullif(btrim(ci.entity_ref::text), '')) as entity,
             coalesce(ci.sectors, '{}'::text[]) as sectors
        from public.circulars ci
    ),
    ds as (
      select d.id, s.v as sector
        from docs d, unnest(d.sectors) s(v)
       where nullif(btrim(s.v), '') is not null
    ),
    sw as (select w.value, w.weight from public.related_axis_weights w
            where w.corpus = 'circular' and w.axis = 'sector'),
    ew as (select w.value, w.weight from public.related_axis_weights w
            where w.corpus = 'circular' and w.axis = 'entity'),

    -- ══════════════════ WAVE E SEAM — topic-BM25 base ══════════════════════
    -- STILL EMPTY. تعاميم have no citations, no clusters and 5 entity values;
    -- one topic sentence per تعميم (search_topics source_type='circular',
    -- 2,119 rows, 1.15/doc) is the only content signal this corpus will ever
    -- have. Until Wave E ships it, تعاميم are BONUS-ONLY.
    --
    -- ⚠ 145 filled the خدمات twin of this seam with vectors, NOT with BM25 —
    -- see the compliance branch. That is not a template for this one: تعاميم
    -- have no embedding of their own, so this seam keeps the plan's original
    -- BM25 contract, INCLUDING its relative normalization.
    --
    -- CONTRACT for the replacement: (a text, b text, base real), one row per
    -- ORDERED pair, BOTH directions, base = 3.0 * bm25 / max_bm25_for_this_
    -- source, i.e. (0, 3.0] normalized per source (plan §3.3 — relative
    -- because BM25 is unbounded and its scale varies with corpus statistics).
    -- Nothing else in this branch changes: `cand` already unions it, `final`
    -- already left-joins it, and `reason` already flips to 'topic_bm25'.
    -- ⚠ Wave E must ALSO emit its own candidates — the axis generators are only
    -- lossless for base = 0 pairs (143 §0), so a topic pair whose base carries
    -- it over the floor has to be generated by the topic side.
    topic_base as (
      select null::text as a, null::text as b, null::real as base where false
    ),
    -- ═══════════════════════════════════════════════════════════════════════

    cand as (
      select u.a, u.b from (
          select a, b from topic_base
        union
          select d1.id as a, d2.id as b
            from docs d1
            join ew on ew.value = d1.entity
                   and ew.weight >= public.related_gen_floor()
            join docs d2 on d2.entity = d1.entity and d2.id <> d1.id
        union
          select p.a, p.b from (
            select x.id as a, y.id as b,
                   least(1.0, (count(*) * (count(*) + 1) / 2.0) * sum(sw.weight))
                     as sector_term
              from ds x
              join ds y  on y.sector = x.sector and y.id <> x.id
              join sw    on sw.value = x.sector
             group by x.id, y.id
          ) p
          where p.sector_term >= public.related_gen_floor()
      ) u
      where u.a is not null and u.b is not null and u.a <> u.b
    ),
    pair_sec as (
      select c.a, c.b, count(*)::int as k,
             sum(sw.weight)::double precision as w_sum
        from cand c
        join ds x on x.id = c.a
        join ds y on y.id = c.b and y.sector = x.sector
        join sw   on sw.value = x.sector
       group by c.a, c.b
    ),
    final as (
      select c.a, c.b,
             coalesce(tb.base, 0)::real as base,
             least(2.0,
                   (case when da.entity is not null and da.entity = db.entity
                         then coalesce(ew.weight, 0) else 0 end)
                 + coalesce(least(1.0, (ps.k * (ps.k + 1) / 2.0) * ps.w_sum), 0)
             )::real as bonus,
             case when coalesce(tb.base, 0) > 0 then 'topic_bm25'
                  else 'bonus_only' end as reason
        from cand c
        join docs da on da.id = c.a
        join docs db on db.id = c.b
        left join topic_base tb on tb.a = c.a and tb.b = c.b
        left join pair_sec   ps on ps.a = c.a and ps.b = c.b
        left join ew            on ew.value = da.entity and da.entity = db.entity
    )
    -- TIEBREAK (145): the same stable shuffle as أنظمة, and it matters MORE
    -- here. تعاميم are bonus-only, so their scores come from a handful of
    -- sector-weight sums and large blocks of candidates tie exactly. The
    -- rejected alternatives are the same two (seo_item_meta.rank is off-limits
    -- under D5; alphabetical front-loads «تعميم…»), plus a third: the wing's
    -- own hub sorts on title, which is precisely the biased option.
    select 'circular', f.a, 'circular', f.b,
           (f.base + f.bonus)::real, f.base, f.bonus, f.reason,
           public.related_stable_tiebreak(f.b)
      from final f
     where (f.base + f.bonus) >= public.related_floor();

  -- ══ خدمات ════════════════════════════════════════════════════════════════
  -- THE BRANCH 145 EXISTS FOR. 143 left this corpus bonus-only and it came back
  -- with 354 edges over 83 of 337 sources; the Wave E seam below is now filled
  -- with services.embedding cosine (see the header, Defect 1).
  elsif p_corpus = 'compliance' then
    delete from public.related_items where source_type = 'compliance';

    insert into public.related_items
      (source_type, source_id, target_type, target_id, score, base, bonus, reason, tiebreak)
    with
    docs as (
      -- The inner select is 143's, unchanged, plus most_used_rank for the
      -- tiebreak. LEFT join to services on purpose: the entity axis and the
      -- corpus membership live on the guide, only the sectors are inherited. A
      -- guide whose service row vanished loses its sectors, not its existence —
      -- the opposite of library_compliance_v's inner join, which is about what
      -- is RENDERABLE. Key space is service_guides.id::text (migration 142),
      -- NOT services.id: the retired 'service' wing left 4,717 rows in the
      -- sidecar under that other key and they are a different corpus entirely.
      --
      -- TIEBREAK (145) = service_guides.most_used_rank, ascending rank = most
      -- used, so the map inverts it: the #1 most-used guide gets 1.0. This is
      -- the ONE corpus where a meaningful tiebreak was available without
      -- touching seo_item_meta — most_used_rank lives on the guide row itself
      -- (142 §confirmed; NULL count was 0 at wing build) and it is already the
      -- /compliance hub's own ordering contract («most used first»), so the
      -- strip and the hub now agree on what "more important" means.
      --   `partition by (most_used_rank is not null)` keeps the unranked out of
      --   the ranked population's denominator; the CASE then sends them to 0 so
      --   they sort last. NOT `order by ... desc nulls last` — cume_dist over a
      --   mixed population would hand the unranked a real value.
      select z.id, z.entity, z.sectors,
             coalesce(
               case when z.most_used_rank is not null
                    then cume_dist() over (
                           partition by (z.most_used_rank is not null)
                           order by z.most_used_rank desc)
               end, 0)::real as tiebreak
        from (
          select g.id::text as id,
                 public.related_canonical_entity(nullif(btrim(g.entity_ref::text), '')) as entity,
                 coalesce(sv.sectors, '{}'::text[]) as sectors,
                 g.most_used_rank
            from public.service_guides g
            left join public.services sv on sv.id = g.service_id
           where coalesce(g.is_canonical, true)
        ) z
    ),
    ds as (
      select d.id, s.v as sector
        from docs d, unnest(d.sectors) s(v)
       where nullif(btrim(s.v), '') is not null
    ),
    sw as (select w.value, w.weight from public.related_axis_weights w
            where w.corpus = 'compliance' and w.axis = 'sector'),
    ew as (select w.value, w.weight from public.related_axis_weights w
            where w.corpus = 'compliance' and w.axis = 'entity'),

    -- ══════════ WAVE E SEAM, FILLED (145) — services.embedding base ════════
    -- INNER joins the whole way down, unlike `docs`: a guide with no service
    -- row, or a service with no embedding, gets no base and keeps its
    -- sector/entity bonus tier. Measured 2026-08-23: 337 of 337 reach one.
    svec as (
      select g.id::text as id, sv.embedding
        from public.service_guides g
        join public.services sv on sv.id = g.service_id
       where coalesce(g.is_canonical, true)
         and sv.embedding is not null
    ),
    -- FULL pairwise cosine. 337 x 336 = 113,232 ordered pairs, ~0.3s. No KNN,
    -- no top-K, no idx_svc_embedding — D6 forbids a top-N per source and an
    -- HNSW index answers a different question ("nearest to this probe") than
    -- the one being asked here. `<=>` is pgvector cosine DISTANCE, so
    -- similarity is 1 - it; same idiom as 101_case_topics_search.sql:147.
    -- Cosine is symmetric and the cross join is unordered, so (a,b) and (b,a)
    -- both fall out naturally — which is the both-directions half of the seam
    -- contract, satisfied without a UNION ALL.
    sim as (
      select x.id as a, y.id as b,
             (1 - (x.embedding <=> y.embedding))::double precision as sim
        from svec x
        join svec y on y.id <> x.id
    ),
    -- The base map. ABSOLUTE, not the plan §3.3 relative form — see the header:
    -- cosine is bounded and comparable across sources, so normalizing by "the
    -- best match for THIS source" would hand a full 3.0 to a guide whose best
    -- neighbour is a mediocre 0.51.
    --     base = 3.0 * (sim - FLOOR) / (MAX - FLOOR),  clamped to (0, 3.0]
    -- Strict `>` on the floor, so the base is never exactly 0 and the seam
    -- contract's (0, 3.0] holds: a pair sitting ON the floor carries no
    -- evidence and must not be labelled as if it did.
    -- greatest(0, …) is belt-and-braces for a future re-fit; nullif guards the
    -- degenerate MAX = FLOOR case.
    topic_base as (
      select s.a, s.b,
             least(3.0, greatest(0.0,
               3.0 * (s.sim - public.related_service_sim_floor())
                   / nullif(public.related_service_sim_max()
                            - public.related_service_sim_floor(), 0)
             ))::real as base
        from sim s
       where s.sim > public.related_service_sim_floor()
    ),
    -- ═══════════════════════════════════════════════════════════════════════

    cand as (
      select u.a, u.b from (
          select a, b from topic_base
        union
          select d1.id as a, d2.id as b
            from docs d1
            join ew on ew.value = d1.entity
                   and ew.weight >= public.related_gen_floor()
            join docs d2 on d2.entity = d1.entity and d2.id <> d1.id
        union
          select p.a, p.b from (
            select x.id as a, y.id as b,
                   least(1.0, (count(*) * (count(*) + 1) / 2.0) * sum(sw.weight))
                     as sector_term
              from ds x
              join ds y  on y.sector = x.sector and y.id <> x.id
              join sw    on sw.value = x.sector
             group by x.id, y.id
          ) p
          where p.sector_term >= public.related_gen_floor()
      ) u
      where u.a is not null and u.b is not null and u.a <> u.b
    ),
    pair_sec as (
      select c.a, c.b, count(*)::int as k,
             sum(sw.weight)::double precision as w_sum
        from cand c
        join ds x on x.id = c.a
        join ds y on y.id = c.b and y.sector = x.sector
        join sw   on sw.value = x.sector
       group by c.a, c.b
    ),
    final as (
      select c.a, c.b,
             coalesce(tb.base, 0)::real as base,
             least(2.0,
                   (case when da.entity is not null and da.entity = db.entity
                         then coalesce(ew.weight, 0) else 0 end)
                 + coalesce(least(1.0, (ps.k * (ps.k + 1) / 2.0) * ps.w_sum), 0)
             )::real as bonus,
             -- 'service_embedding', NOT 'topic_bm25' — different evidence, and
             -- Wave D samples on this column.
             case when coalesce(tb.base, 0) > 0 then 'service_embedding'
                  else 'bonus_only' end as reason,
             db.tiebreak
        from cand c
        join docs da on da.id = c.a
        join docs db on db.id = c.b
        left join topic_base tb on tb.a = c.a and tb.b = c.b
        left join pair_sec   ps on ps.a = c.a and ps.b = c.b
        left join ew            on ew.value = da.entity and da.entity = db.entity
    )
    select 'compliance', f.a, 'compliance', f.b,
           (f.base + f.bonus)::real, f.base, f.bonus, f.reason, f.tiebreak
      from final f
     where (f.base + f.bonus) >= public.related_floor();

  -- ══ أحكام ════════════════════════════════════════════════════════════════
  -- No base axis at all (plan §3.3): base = 0.0 always, court carries the
  -- signal through the bonus. bonus = least(2.0, entity_term + w(court)).
  --
  -- ⚠ THIS IS THE BRANCH THE GUARDS EXIST FOR. An unguarded court self-join is
  --   932M pairs. The generation threshold admits only courts and entities with
  --   w >= FLOOR/2, i.e. n <= ~780 of 30,531 — so التجارية (~22k rows, w ~1e-4)
  --   and وزارة العدل (20,671, w 0.0002) generate NOTHING, which is also why
  --   ~75% of judgment pages will correctly show no strip.
  --
  -- ⚠ AND IT IS THE BRANCH THE TIEBREAK EXISTS FOR (Defect 2). Because court
  --   and entity are both constant inside a court, every surviving candidate
  --   for a given judgment carries the SAME bonus and therefore the same score.
  --   Recency is the only ordering left that a reader would recognise.
  elsif p_corpus = 'judgment' then
    delete from public.related_items where source_type = 'judgment';

    insert into public.related_items
      (source_type, source_id, target_type, target_id, score, base, bonus, reason, tiebreak)
    with
    docs as (
      -- The inner select is 143's, unchanged, plus the effective date.
      --
      -- TIEBREAK (145) = recency of the TARGET ruling, newest first.
      --   Coverage measured 2026-08-23 over 30,531 rows: date_gregorian 19,112,
      --   date_hijri 26,979. Both are handled and so is neither.
      --   • date_gregorian first, guarded by a regex rather than a bare cast.
      --     The guard is type-agnostic (a `date` renders as YYYY-MM-DD under
      --     ::text at the default DateStyle 'ISO, MDY', a text column passes
      --     through unchanged) and, more importantly, it CANNOT THROW: an
      --     unparseable value falls through to the Hijri path instead of
      --     aborting a 13-minute backfill at minute nine. A session running
      --     with a non-ISO DateStyle would degrade the whole corpus to the
      --     Hijri path rather than corrupt it — §7(e)'s second query is the
      --     check that catches that, since it counts dated rulings that came
      --     back with tiebreak 0.
      --   • date_hijri second, via related_hijri_date() — year precision only,
      --     pinned to 1 July. Every ruling known only to its Hijri year lands
      --     on one of ~20 dates and those rows tie with EACH OTHER. That
      --     residual tie is not a defect; it is the precision the data has.
      --   • Neither -> d is NULL -> tiebreak 0, which sorts LAST and is not
      --     NULL (the column is not null). This inversion is the trap the whole
      --     construction is arranged around: Postgres puts NULLs FIRST on a
      --     DESC order, and the judgments hub already carries a `nullsfirst=
      --     False` comment saying this exact bug has bitten this codebase.
      --   • cume_dist, not a min/max rescale: it is rank-based, so one bogus
      --     1899 or 2099 date cannot compress every real ruling into the top
      --     percent of the range. Only monotonicity is ever read.
      --   • `partition by (d is not null)` keeps the dateless out of the dated
      --     population's denominator, so the newest dated ruling is exactly 1.0
      --     and the oldest is 1/~27,000 — still strictly above 0 and still
      --     resolvable in float4 (1/27,000 = 3.7e-5, eps near 1.0 is 1.2e-7).
      --   • greatest()/least() are deliberately NOT used to clamp: they IGNORE
      --     NULLs in Postgres, so `greatest(NULL, date '1900-01-01')` returns
      --     1900-01-01 and would silently turn every dateless ruling into the
      --     OLDEST one instead of the last one.
      select z.id, z.entity, z.court,
             coalesce(
               case when z.d is not null
                    then cume_dist() over (partition by (z.d is not null)
                                           order by z.d)
               end, 0)::real as tiebreak
        from (
          select c.id::text as id,
                 public.related_canonical_entity(c.entity_id::text) as entity,
                 nullif(btrim(c.court), '') as court,
                 case
                   when c.date_gregorian::text ~ '^\d{4}-\d{2}-\d{2}'
                     then substring(c.date_gregorian::text from 1 for 10)::date
                   else public.related_hijri_date(c.date_hijri::text)
                 end as d
            from public.cases c
        ) z
    ),
    cw as (select w.value, w.weight from public.related_axis_weights w
            where w.corpus = 'judgment' and w.axis = 'court'),
    ew as (select w.value, w.weight from public.related_axis_weights w
            where w.corpus = 'judgment' and w.axis = 'entity'),
    cand as (
      select u.a, u.b from (
          -- court generator. w(court) >= FLOOR/2 means n <= ~780 of 30,531, so
          -- التجارية and وزارة العدل never enter — which is the whole reason
          -- this is ~1.5M rows and not 932M.
          select d1.id as a, d2.id as b
            from docs d1
            join cw on cw.value = d1.court
                   and cw.weight >= public.related_gen_floor()
            join docs d2 on d2.court = d1.court and d2.id <> d1.id
        union
          select d1.id as a, d2.id as b
            from docs d1
            join ew on ew.value = d1.entity
                   and ew.weight >= public.related_gen_floor()
            join docs d2 on d2.entity = d1.entity and d2.id <> d1.id
      ) u
      where u.a is not null and u.b is not null and u.a <> u.b
    ),
    final as (
      select c.a, c.b,
             0::real as base,
             least(2.0,
                   (case when da.entity is not null and da.entity = db.entity
                         then coalesce(ew.weight, 0) else 0 end)
                 + (case when da.court is not null and da.court = db.court
                         then coalesce(cw.weight, 0) else 0 end)
             )::real as bonus,
             'bonus_only'::text as reason,
             db.tiebreak            -- the TARGET's recency; db is already joined
        from cand c
        join docs da on da.id = c.a
        join docs db on db.id = c.b
        left join ew on ew.value = da.entity and da.entity = db.entity
        left join cw on cw.value = da.court  and da.court  = db.court
    )
    select 'judgment', f.a, 'judgment', f.b,
           (f.base + f.bonus)::real, f.base, f.bonus, f.reason, f.tiebreak
      from final f
     where (f.base + f.bonus) >= public.related_floor();

  else
    raise exception 'refresh_related_items: unknown corpus %', p_corpus;
  end if;

  get diagnostics v_count = row_count;
  return v_count;
end $$;

